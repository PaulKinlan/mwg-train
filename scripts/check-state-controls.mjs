#!/usr/bin/env node
/**
 * check:state-controls - a brief that depicts a Light/Dark twin pair must say which option of its
 * two-option theme control is active, and that answer must follow the theme the board depicts.
 *
 * The boards in `docs/design/archetypes/<family>/` are read as pairs: the same step rendered Light and
 * Dark is what a reader compares to see the interface respond to its own theme switch. A control that
 * emphasises the same segment in both twins therefore says one of two things, and both are wrong - either
 * the fill is decoration and the control conveys no state at all, or the state contradicts the page it
 * sits on. Signal Grid's eight committed boards had exactly that defect (mwg-train-zeci): every board,
 * including the four night-mode ones, marked the DAYLIGHT segment.
 *
 * The defect is text, not CSS. The committed JPEGs are illustrative and cannot be edited in place, and a
 * replacement needs amount-scoped approval that has not been given, so the pass/fail is the generation
 * brief: the prompt a future generation reads. This check holds that brief to the control's contract.
 *
 * What it checks, in order (each is a finding, not a warning):
 *
 *   1. The family's README carries a `## Theme-control state` section that requires the active segment to
 *      be filled AND marked, and the other segment unmarked. A fill-only rule is the ambiguity below:
 *      a tint difference that never changes between twins reads as decoration.
 *   2. The section's table lists exactly the committed boards, once each, so a board cannot be added
 *      without stating the control state it must show.
 *   3. Each row's active segment is the one its declared theme selects, so the table cannot claim a night
 *      board marks DAYLIGHT active.
 *   4. A board stored under `dark/` is declared Night. The directory names the theme, so this is the one
 *      theme fact about the unrecorded Dark twins that the tree itself establishes.
 *   5. Every authored prompt block carries the exact clause for its row's theme (filled, check glyph, the
 *      other segment flat and unmarked) and does not carry the clause for the other theme. The clause is
 *      generated by `activeSegmentClause`, so the brief and this check cannot drift into paraphrases.
 *   6. A prompt's declared theme phrase agrees with its row, so the table cannot be made to pass by
 *      relabelling every board as Light while the prompts still say NIGHT MODE.
 *   7. Each Light/Dark twin pair whose themes differ marks different segments - the invariant the bead
 *      asks for - and at least one pair does differ, so a table rewritten to a single theme fails instead
 *      of passing vacuously.
 *
 * The check is deliberately about the brief, not about the committed pixels: a still JPEG cannot show
 * that the control has a state, and reading the pill back out of eight images is a different (and much
 * more brittle) gate than the one this defect needs. It reads the authored text only - no image decode,
 * no network, no browser - so it runs in `npm run build` and the fast gate.
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import process from 'node:process';

const ROOT = resolve(import.meta.dirname, '..');
const ARCHETYPES_DIR = join(ROOT, 'docs', 'design', 'archetypes');

/** The families whose brief declares a two-option theme control. */
export const SUBJECTS = ['browser-puzzle-game'];

/** The section a subject's README must carry, and the heading the table lives under. */
export const SECTION = 'Theme-control state';

const BOARD = /^step\d+[a-z0-9-]*\.jpg$/;

/**
 * Signal Grid names its theme in one fixed phrase. The pill clause names BOTH segments, so a bare
 * DAYLIGHT/NIGHT token cannot tell the depicted theme from the control's state; reading the mode phrase
 * keeps the two separable.
 */
const DEPICTED_THEME_PHRASES = [
  { theme: 'Light', phrase: 'TACTILE DAYLIGHT ARCADE MODE' },
  { theme: 'Night', phrase: 'OLED SYNTH NIGHT MODE' },
];

const SEGMENT_FOR_THEME = { Light: 'DAYLIGHT', Night: 'NIGHT' };
const PILL = '“Daylight / Night”';

const squash = (text) => text.replace(/\s+/g, ' ').trim();

/**
 * The clause every prompt for a board of `theme` must carry, verbatim. Generated rather than quoted so a
 * wording change lands in the brief and this check together.
 */
export function activeSegmentClause(theme) {
  if (!SEGMENT_FOR_THEME[theme]) throw new Error(`no theme '${theme}'; known themes are ${Object.keys(SEGMENT_FOR_THEME).join(', ')}`);
  const active = SEGMENT_FOR_THEME[theme];
  const inactive = active === 'DAYLIGHT' ? 'NIGHT' : 'DAYLIGHT';
  return `the ${PILL} theme pill shows the ${active} segment filled with a check glyph and the ${inactive} segment flat and unmarked`;
}

export function sectionBody(readmeText, heading = SECTION) {
  const start = readmeText.indexOf(`## ${heading}`);
  if (start === -1) return null;
  const rest = readmeText.slice(start + heading.length + 3);
  const next = rest.indexOf('\n## ');
  return next === -1 ? rest : rest.slice(0, next);
}

const ROW = /^\|\s*`([^`]+)`\s*\|\s*(Light|Night)\s*\|\s*`(DAYLIGHT|NIGHT)`\s*\|$/;

/** Rows of the section table, plus every table line that is not one (those are findings, not noise). */
export function parseRows(sectionText) {
  const rows = [];
  const unparseable = [];
  for (const line of sectionText.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed.startsWith('|')) continue;
    if (/^\|\s*:?-{3,}/.test(trimmed)) continue;
    if (/^\|\s*Board\s*\|/i.test(trimmed)) continue;
    const match = ROW.exec(trimmed);
    if (!match) {
      unparseable.push(trimmed);
      continue;
    }
    rows.push({ board: match[1], theme: match[2], active: match[3] });
  }
  return { rows, unparseable };
}

/** The authored prompt blocks. Same shape `extractPrompts` reads in the board generator. */
export function parsePrompts(readmeText) {
  const prompts = new Map();
  for (const match of readmeText.matchAll(/###\s*`(step\d+[a-z0-9-]*\.jpg)`\s*\n+```text\n([\s\S]*?)\n```/g)) {
    prompts.set(match[1], match[2]);
  }
  return prompts;
}

/** Every board the family commits: the step JPEGs, plus their Dark twins when the directory exists. */
export function boardsOnDisk(dir) {
  const direct = readdirSync(dir).filter((name) => BOARD.test(name)).sort();
  const darkDir = join(dir, 'dark');
  const dark = existsSync(darkDir)
    ? readdirSync(darkDir).filter((name) => BOARD.test(name)).sort().map((name) => `dark/${name}`)
    : [];
  return [...direct, ...dark];
}

/** Pure verdict, so the cases that must fail can be tested without a second README on disk. */
export function stateControlFindings({ family = SUBJECTS[0], readmeText, boards }) {
  const findings = [];
  const add = (code, message) => findings.push({ code, family, message });

  const section = sectionBody(readmeText);
  if (section === null) {
    add('SECTION_MISSING', `${family}: README has no '## ${SECTION}' section, so nothing states which segment of the two-option theme control is active`);
    return findings;
  }
  if (!/filled/.test(section) || !/(check|dot)/.test(section) || !/unmarked/.test(section)) {
    add('MARKER_RULE_MISSING', `${family}: '## ${SECTION}' must require the ACTIVE segment to be filled AND carry a check or dot glyph, and the other segment unmarked; a fill-only rule is what made the committed boards ambiguous`);
  }

  const { rows, unparseable } = parseRows(section);
  for (const line of unparseable) {
    add('ROW_UNPARSEABLE', `${family}: '## ${SECTION}' has a table row this check cannot read: ${line}`);
  }
  const byBoard = new Map();
  for (const row of rows) {
    if (byBoard.has(row.board)) add('ROW_DUPLICATE', `${family}: ${row.board} is declared more than once; one row per committed board`);
    byBoard.set(row.board, row);
    if (!boards.includes(row.board)) add('ROW_WITHOUT_BOARD', `${family}: ${row.board} is declared but no such board is committed`);
    if (SEGMENT_FOR_THEME[row.theme] !== row.active) {
      add('ACTIVE_SEGMENT_DOES_NOT_TRACK_THEME', `${family}: ${row.board} is declared ${row.theme} but marks ${row.active} active; the ACTIVE segment must be the one the depicted theme selects`);
    }
    if (row.board.startsWith('dark/') && row.theme !== 'Night') {
      add('DARK_TWIN_NOT_NIGHT', `${family}: ${row.board} lives under dark/ but is declared ${row.theme}; the directory names the theme it depicts`);
    }
  }
  for (const board of boards) {
    if (!byBoard.has(board)) add('BOARD_UNLISTED', `${family}: ${board} is committed but no row states its control state, so a regeneration is unconstrained`);
  }

  const prompts = parsePrompts(readmeText);
  for (const [board, prompt] of prompts) {
    const row = byBoard.get(board);
    if (!row) {
      add('PROMPT_WITHOUT_ROW', `${family}: prompt ${board} has no table row, so its control state is unconstrained`);
      continue;
    }
    const text = squash(prompt);
    const declared = DEPICTED_THEME_PHRASES.filter(({ phrase }) => text.includes(phrase));
    if (declared.length !== 1) {
      add('PROMPT_THEME_AMBIGUOUS', `${family}: prompt ${board} must name exactly one depicted-theme phrase (${DEPICTED_THEME_PHRASES.map(({ phrase }) => phrase).join(' / ')}); found ${declared.length}`);
    } else if (declared[0].theme !== row.theme) {
      add('PROMPT_THEME_DISAGREES_WITH_ROW', `${family}: prompt ${board} says ${declared[0].phrase} but its row declares ${row.theme}`);
    }
    if (!text.includes(activeSegmentClause(row.theme))) {
      add('PROMPT_MISSING_CONTROL_STATE', `${family}: prompt ${board} must carry, verbatim, "${activeSegmentClause(row.theme)}" (row theme ${row.theme})`);
    }
    const other = activeSegmentClause(row.theme === 'Light' ? 'Night' : 'Light');
    if (text.includes(other)) {
      add('PROMPT_CONTRADICTS_CONTROL_STATE', `${family}: prompt ${board} carries the ${row.theme === 'Light' ? 'Night' : 'Light'} board's clause: "${other}"`);
    }
  }

  const pairs = rows
    .filter((row) => row.board.startsWith('dark/'))
    .map((darkRow) => ({ dark: darkRow, light: byBoard.get(darkRow.board.slice('dark/'.length)) }))
    .filter(({ light }) => light !== undefined);
  let contrasted = 0;
  for (const { dark, light } of pairs) {
    if (dark.theme === light.theme) continue;
    if (dark.active === light.active) {
      add('TWIN_PAIR_INVARIANT', `${family}: ${light.board} (${light.theme}) and ${dark.board} (${dark.theme}) both mark ${light.active} active, so the pair cannot show the control following the theme - the defect this check exists to prevent`);
    } else {
      contrasted += 1;
    }
  }
  if (contrasted === 0) {
    add('TWIN_PAIR_WITHOUT_CONTRAST', `${family}: no Light/Dark twin pair is declared with different themes, so this table cannot show the control tracking the theme`);
  }

  return findings;
}

function main() {
  const findings = [];
  for (const family of SUBJECTS) {
    const dir = join(ARCHETYPES_DIR, family);
    const readmePath = join(dir, 'README.md');
    if (!existsSync(readmePath)) {
      findings.push({ code: 'README_MISSING', family, message: `${family}: no README at ${readmePath}` });
      continue;
    }
    findings.push(...stateControlFindings({
      family,
      readmeText: readFileSync(readmePath, 'utf8'),
      boards: boardsOnDisk(dir),
    }));
  }
  for (const finding of findings) console.log(`FINDING ${finding.code} ${finding.message}`);
  if (findings.length > 0) {
    console.error(`check-state-controls: FAIL - ${findings.length} finding(s) across ${SUBJECTS.length} brief(s)`);
    process.exit(1);
  }
  console.log(`check-state-controls: PASS - ${SUBJECTS.length} brief(s) state which theme segment is active, and the twins contrast`);
}

if (process.argv[1] === resolve(import.meta.filename)) main();
