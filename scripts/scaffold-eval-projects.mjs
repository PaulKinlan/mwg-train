#!/usr/bin/env node
/**
 * Generate the evaluation control fixtures from `docs/eval/projects/fixtures.mjs`, and check that the
 * tree on disk still matches.
 *
 *   node scripts/scaffold-eval-projects.mjs            # write the projects and their content hashes
 *   node scripts/scaffold-eval-projects.mjs --check    # re-derive and fail on any drift
 *
 * The projects are committed, not generated at run time, because a baseline that could change between
 * the moment it is promised and the moment it is run against is not a baseline. `--check` is the gate:
 * it re-derives every file and every content hash and compares them to what is committed, so an edit
 * to a fixture shows up as a failing check rather than as an unexplained result.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import process from 'node:process';

import { FIXTURES, fixturePath } from '../docs/eval/projects/fixtures.mjs';
import { snapshotPages, treeSnapshot } from '../src/eval/baseline.mjs';
import { createRoutes, openStore } from '../src/eval/site-kit.mjs';

const ROOT = resolve(process.cwd());
const RELATIVE_KIT = '../../../../../src/eval/site-kit.mjs';

function serverSource() {
  return `// Generated by scripts/scaffold-eval-projects.mjs from docs/eval/projects/fixtures.mjs.
// Run with: node server.mjs   (prints SITE_READY <port> once it is listening)
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { createRoutes, openStore, serve } from '${RELATIVE_KIT}';

const here = dirname(fileURLToPath(import.meta.url));
export const spec = JSON.parse(readFileSync(join(here, 'spec.json'), 'utf8'));
export const routes = createRoutes(spec, openStore(join(here, 'data.json'), spec.seed ?? {}));

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  const { port } = await serve(routes);
  console.log(\`SITE_READY \${port}\`);
}
`;
}

function packageSource(fixture) {
  return `${JSON.stringify({ name: `eval-${fixture.project_id}`, private: true, type: 'module', scripts: { start: 'node server.mjs' } }, null, 2)}\n`;
}

function specSource(fixture) {
  const { group, brief_id, family_id, defects_note, ...spec } = fixture;
  return `${JSON.stringify(spec, null, 2)}\n`;
}

/** Every GET route, with `:id` replaced by the first seeded record so it can be rendered. */
function snapshotPaths(fixture) {
  return (fixture.pages ?? []).map((pageSpec) => pageSpec.path.replace(/:([A-Za-z0-9_]+)/g, () => fixture.seed?.[pageSpec.collection]?.[0]?.id ?? '1'));
}

async function snapshotSource(fixture, { store }) {
  const routes = createRoutes(fixture, store);
  const pages = await snapshotPages(routes, snapshotPaths(fixture));
  return { pages };
}

async function snapshotBody(fixture) {
  const { mkdtempSync } = await import('node:fs');
  const { tmpdir } = await import('node:os');
  const dir = mkdtempSync(join(tmpdir(), 'eval-snapshot-'));
  const snapshot = await snapshotSource(fixture, { store: openStore(join(dir, 'data.json'), fixture.seed ?? {}) });
  return `${JSON.stringify(snapshot, null, 2)}\n`;
}

function projectFiles(fixture) {
  return { 'spec.json': specSource(fixture), 'server.mjs': serverSource(), 'package.json': packageSource(fixture) };
}

function expectedTree(projectDir) {
  return treeSnapshot(projectDir);
}

function write(files) {
  for (const [path, contents] of Object.entries(files)) writeFileSync(path, contents);
}

function check(files) {
  const drift = [];
  for (const [path, contents] of Object.entries(files)) {
    let actual = null;
    try {
      actual = readFileSync(path, 'utf8');
    } catch {
      drift.push(`missing ${path}`);
      continue;
    }
    if (actual !== contents) drift.push(`changed ${path}`);
  }
  return drift;
}

function main() {
  return mainInner();
}

async function mainInner() {
  const mode = process.argv.includes('--check') ? 'check' : 'write';
  const index = {};
  const drift = [];
  for (const fixture of FIXTURES) {
    const projectDir = resolve(ROOT, fixturePath(fixture));
    const files = projectFiles(fixture);
    const absolute = Object.fromEntries(Object.entries(files).map(([name, contents]) => [join(projectDir, name), contents]));
    const treePath = join(projectDir, 'tree.json');
    const snapshotPath = join(projectDir, 'snapshot.json');
    const snapshot = await snapshotBody(fixture);
    if (mode === 'write') {
      mkdirSync(projectDir, { recursive: true });
      write(absolute);
      writeFileSync(snapshotPath, snapshot);
      const tree = expectedTree(projectDir);
      writeFileSync(treePath, `${JSON.stringify(tree, null, 2)}\n`);
      index[fixture.project_id] = { group: fixture.group, brief_id: fixture.brief_id ?? null, family_id: fixture.family_id ?? null, path: fixturePath(fixture), tree: tree.tree, files: tree.count };
      continue;
    }
    drift.push(...check({ ...absolute, [snapshotPath]: snapshot }));
    const committed = JSON.parse(readFileSync(treePath, 'utf8'));
    const derived = expectedTree(projectDir);
    if (committed.tree !== derived.tree) drift.push(`tree.json is stale for ${fixture.project_id}: committed ${committed.tree} derived ${derived.tree}`);
    index[fixture.project_id] = { group: fixture.group, brief_id: fixture.brief_id ?? null, family_id: fixture.family_id ?? null, path: fixturePath(fixture), tree: committed.tree, files: committed.count };
  }
  const indexPath = resolve(ROOT, 'docs/eval/projects/index.json');
  if (mode === 'write') {
    writeFileSync(indexPath, `${JSON.stringify({ fixtures: index }, null, 2)}\n`);
    console.log(`scaffold-eval-projects: wrote ${FIXTURES.length} fixtures`);
  } else {
    const committedIndex = JSON.parse(readFileSync(indexPath, 'utf8'));
    if (JSON.stringify(committedIndex.fixtures) !== JSON.stringify(index)) drift.push('index.json is stale');
    if (drift.length) {
      for (const item of drift) console.error(`scaffold-eval-projects: ${item}`);
      process.exit(1);
    }
    console.log(`scaffold-eval-projects: ${FIXTURES.length} fixtures match`);
  }
}

await main();
